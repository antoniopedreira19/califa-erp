const { chromium } = require(process.env.PLAYWRIGHT ?? 'playwright');
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: 1960, height: 1500 } });
  const erros = [];
  p.on('pageerror', e => erros.push(e.message));
  await p.goto('file://' + process.cwd() + '/conciliacao-banco.html');
  await p.click('text=Esconder notas');
  const txt = async (sel) => (await p.innerText(sel)).replace(/\s+/g, ' ');
  const out = {};
  await p.click('.pg-seg >> text=Conciliação · Conciliação automática');
  await p.click('button:has-text("Usar o extrato de exemplo")');
  await p.waitForTimeout(400);
  out.resumo = (await txt('body')).match(/se resolveram sozinhas:[^.]*\)/)?.[0];
  await p.click('button:has-text("Corrigir a baixa")');
  await p.waitForTimeout(120);
  out.dialogo = await txt('[role=dialog]');
  await p.locator('[role=dialog]').screenshot({ path: 'test/37-corrigir.png' });
  await p.click('[role=dialog] button:has-text("Corrigir e conciliar")');
  out.semMotivo = (await txt('[role=dialog]')).match(/Registre o motivo[^.]*\./)?.[0];
  await p.click('[role=dialog] button:has-text("O banco não cobrou")');
  out.motivo = await p.inputValue('#corrigir-motivo');
  await p.click('[role=dialog] button:has-text("Corrigir e conciliar")');
  await p.waitForTimeout(120);
  out.fechou = await p.locator('[role=dialog]').count();
  out.toast = (await txt('body')).match(/Baixa corrigida para[^.]*\.[^.]*\./)?.[0];
  out.conciliado = (await txt('body')).match(/Baixa corrigida de[^”]*”/)?.[0];
  // O ⓘ do lançamento no Extrato
  await p.click('.pg-seg >> text=Conciliação · Extrato');
  await p.waitForTimeout(150);
  const linha = p.locator('tr', { hasText: 'Manutenção do ar-condicionado' }).first();
  out.linha = (await linha.innerText()).replace(/\s+/g, ' ').slice(0, 160);
  await linha.locator('button[aria-label^="Ver detalhes"]').first().click();
  await p.waitForTimeout(150);
  out.historico = (await txt('body')).match(/HISTÓRICO DA BAIXA.{0,220}/i)?.[0];
  await p.screenshot({ path: 'test/37-info.png', fullPage: false });
  await p.keyboard.press('Escape');
  // Desfazer: volta a divergência e o histórico ganha o desfazer
  await p.click('.pg-seg >> text=Conciliação · Conciliação automática');
  await p.waitForTimeout(100);
  const sec = p.locator('button:has-text("Conciliados")').first();
  if (await sec.count()) await sec.click();
  out.conciliado = (await txt('body')).match(/Baixa corrigida de[^”]*”/)?.[0];
  const alvo = p.locator('tr', { hasText: 'Baixa corrigida de' });
  out.alvos = await alvo.count();
  await alvo.last().locator('button[aria-label="Desfazer"]').click();
  await p.waitForTimeout(120);
  out.voltou = await p.locator('button:has-text("Corrigir a baixa")').count();
  await p.click('.pg-seg >> text=Conciliação · Extrato');
  await p.waitForTimeout(150);
  await p.locator('tr', { hasText: 'Manutenção do ar-condicionado' }).first().locator('button[aria-label^="Ver detalhes"]').first().click();
  await p.waitForTimeout(150);
  out.linhas2 = await p.locator('tr', { hasText: 'Manutenção do ar-condicionado' }).count();
  if (!/HISTÓRICO DA BAIXA/i.test(await txt('body'))) { await p.locator('tr', { hasText: 'Manutenção do ar-condicionado' }).first().locator('button[aria-label^="Ver detalhes"]').first().click(); await p.waitForTimeout(150); }
  out.historico2 = (await txt('body')).match(/HISTÓRICO DA BAIXA.{0,300}/i)?.[0];
  await p.screenshot({ path: 'test/37-info2.png' });
  console.log(JSON.stringify(out, null, 1), erros);
  await b.close();
})();
