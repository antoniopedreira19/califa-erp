const UNID = ["", "um", "dois", "três", "quatro", "cinco", "seis", "sete", "oito", "nove"];
const DEZ_A_DEZENOVE = ["dez", "onze", "doze", "treze", "quatorze", "quinze", "dezesseis", "dezessete", "dezoito", "dezenove"];
const DEZENAS = ["", "", "vinte", "trinta", "quarenta", "cinquenta", "sessenta", "setenta", "oitenta", "noventa"];
const CENTENAS = ["", "cento", "duzentos", "trezentos", "quatrocentos", "quinhentos", "seiscentos", "setecentos", "oitocentos", "novecentos"];

function ate999(n) {
  if (n === 100) return "cem";
  const c = Math.floor(n / 100), r = n % 100, partes = [];
  if (c) partes.push(CENTENAS[c]);
  if (r) {
    if (r < 10) partes.push(UNID[r]);
    else if (r < 20) partes.push(DEZ_A_DEZENOVE[r - 10]);
    else partes.push(DEZENAS[Math.floor(r / 10)] + (r % 10 ? " e " + UNID[r % 10] : ""));
  }
  return partes.join(" e ");
}

function inteiroPorExtenso(n) {
  if (n === 0) return "zero";
  const mi = Math.floor(n / 1e6), mil = Math.floor((n % 1e6) / 1000), un = n % 1000;
  const grupos = [];
  if (mi) grupos.push({ v: mi, t: mi === 1 ? "um milhão" : ate999(mi) + " milhões" });
  if (mil) grupos.push({ v: mil, t: mil === 1 ? "mil" : ate999(mil) + " mil" });
  if (un) grupos.push({ v: un, t: ate999(un) });
  return grupos.reduce((acc, g, i) => {
    if (i === 0) return g.t;
    const ultimo = i === grupos.length - 1;
    // "mil e quinhentos", "mil e vinte" — mas "mil duzentos e trinta".
    const comE = ultimo && (g.v < 100 || g.v % 100 === 0);
    return acc + (comE ? " e " : ultimo ? " " : ", ") + g.t;
  }, "");
}

function porExtenso(valor) {
  const total = Math.round((valor || 0) * 100);
  const reais = Math.floor(total / 100), centavos = total % 100;
  const partes = [];
  if (reais) {
    const milhaoRedondo = reais >= 1e6 && reais % 1e6 === 0;
    partes.push(inteiroPorExtenso(reais) + (reais === 1 ? " real" : milhaoRedondo ? " de reais" : " reais"));
  }
  if (centavos) partes.push(inteiroPorExtenso(centavos) + (centavos === 1 ? " centavo" : " centavos"));
  return partes.length ? partes.join(" e ") : "zero real";
}
